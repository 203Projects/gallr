Deno.test("inspectImageBytes validates and decodes a complete PNG", async () => {
  const result = await inspectImageBytes(VALID_ONE_PIXEL_PNG);
  assert(result.mimeType === "image/png", "expected PNG MIME");
  assert(result.width === 1, "expected width 1");
  assert(result.height === 1, "expected height 1");
  assert(
    result.byteSize === VALID_ONE_PIXEL_PNG.byteLength,
    "expected exact byte size",
  );
  assert(/^[0-9a-f]{64}$/.test(result.checksumSha256), "expected SHA-256");
});

Deno.test("inspectImageBytes validates and decodes a complete JPEG", async () => {
  const result = await inspectImageBytes(VALID_ONE_PIXEL_JPEG);
  assert(result.mimeType === "image/jpeg", "expected JPEG MIME");
  assert(result.width === 1 && result.height === 1, "expected 1x1 dimensions");
  assert(
    result.byteSize === VALID_ONE_PIXEL_JPEG.byteLength,
    "expected exact byte size",
  );
});

