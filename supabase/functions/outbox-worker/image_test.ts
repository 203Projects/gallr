Deno.test("inspectImageBytes rejects a structurally truncated PNG", async () => {
  try {
    await inspectImageBytes(VALID_ONE_PIXEL_PNG.subarray(0, -1));
    throw new Error("expected validation failure");
  } catch (error) {
    assert(
      error instanceof ImageValidationError,
      "expected ImageValidationError",
    );
    assert(
      error.code === "png_chunk_invalid",
      "expected full-container validation",
    );
  }
});

Deno.test("inspectImageBytes rejects unsupported bytes deterministically", async () => {
  try {
    await inspectImageBytes(new Uint8Array([1, 2, 3, 4, 5]));
    throw new Error("expected validation failure");
  } catch (error) {
    assert(
      error instanceof ImageValidationError,
      "expected ImageValidationError",
    );
    assert(
      error.code === "image_magic_unsupported",
      "expected stable reason code",
    );
  }
});
